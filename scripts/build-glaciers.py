"""
Build src/imagery/glaciers.ts: where on Earth a time-lapse's 10 km square holds glacier ice.

The time-lapse shows glaciers in one season every year (seasonRegions.ts). It needs to know, offline and in a few
kilobytes, whether a place's square has ice in it: a grid of 0.1° cells, a cell set when ice lies within NEAR_KM
north, south, east or west of any part of it (the square reaches FRAME_HALF_KM = 5 km each way), each row
run-length encoded.

Source: Natural Earth 10m glaciated areas v5.1.2 (public domain), which leaves out Antarctica (the app takes all of
it south of 60° S as ice):
  https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_10m_glaciated_areas.geojson

Usage:
  python3 scripts/build-glaciers.py <ne_10m_glaciated_areas.geojson>
Needs numpy, scipy and Pillow.
"""
import json, math, sys
import numpy as np
from PIL import Image, ImageDraw
from scipy import ndimage

CELL = 0.1  # degrees; a cell is 11 km north–south, 5.5 km east–west at 60°
NEAR_KM = 5.0  # the square's half side
SS = 4  # supersampling, so a glacier smaller than a cell still sets it
KM_PER_DEG = 111.32
OUT = 'src/imagery/glaciers.ts'

W, H = round(360 / CELL), round(180 / CELL)


def rasterise(path):
    img = Image.new('1', (W * SS, H * SS), 0)
    draw = ImageDraw.Draw(img)
    for f in json.load(open(path))['features']:
        g = f['geometry']
        polys = g['coordinates'] if g['type'] == 'MultiPolygon' else [g['coordinates']]
        for poly in polys:
            ring = [((x + 180) / CELL * SS, (90 - y) / CELL * SS) for x, y in poly[0]]
            draw.polygon(ring, fill=1, outline=1)
    return np.array(img, dtype=bool).reshape(H, SS, W, SS).any(axis=(1, 3))


def grow(ice):
    """Set every cell with ice within NEAR_KM of it, along the axes (the square is a square, not a circle)."""
    out = ice.copy()
    ky = math.ceil(NEAR_KM / (CELL * KM_PER_DEG))
    for r in range(H):
        band = ice[max(0, r - ky) : r + ky + 1].any(axis=0)
        if not band.any():
            continue
        lat = 90 - (r + 0.5) * CELL
        kx = math.ceil(NEAR_KM / (CELL * KM_PER_DEG * max(math.cos(math.radians(lat)), 0.05)))
        out[r] |= ndimage.binary_dilation(band, iterations=kx)
    return out


def encode(grid):
    """Rows north to south, ';' between rows: the row's step from the last one, then gap, length, gap, length… (base 36)."""
    rows, last = [], 0
    for r in range(H):
        row = grid[r]
        if not row.any():
            continue
        edges = np.flatnonzero(np.diff(np.concatenate([[0], row.astype(np.int8), [0]]))).reshape(-1, 2)
        nums, end = [r - last], 0
        for s, e in edges:
            nums += [s - end, e - s]
            end = e
        rows.append(','.join(np.base_repr(n, 36).lower() for n in nums))
        last = r
    return ';'.join(rows)


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    grid = grow(rasterise(sys.argv[1]))
    data = encode(grid)
    body = f"""/**
 * Where a time-lapse's 10 km square holds glacier ice, as a grid of {CELL}° cells (rows from 90° N, columns from
 * 180° W), each row run-length encoded. Generated by scripts/build-glaciers.py from Natural Earth 10m glaciated
 * areas v5.1.2 (public domain): a cell is set when ice lies within {NEAR_KM:g} km of it along either axis. Do not edit.
 */
export const GLACIER_CELL = {CELL}
export const GLACIER_ROWS = '{data}'
"""
    open(OUT, 'w').write(body)
    print(f'{OUT}: {int(grid.sum())} cells, {len(data)} bytes')


if __name__ == '__main__':
    main()
