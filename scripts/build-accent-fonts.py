#!/usr/bin/env python3
"""
Build the serif accent faces for Chinese, Japanese and Korean: src/i18n/<locale>/accentFont.gen.ts.

Why: the design's one serif moment per screen (the hero's "you", the About title's accent) is a serif in signal orange.
CJK has no italic, and the platforms' own serifs are missing on most Windows and Android installs, so the hero would
fall back to a sans on half the screens. The accent words are fixed copy, so we ship exactly their glyphs from Noto
Serif CJK (SIL OFL 1.1): a few kB per language, embedded in that language's messages chunk (src/i18n/accentFont.ts
installs it with the FontFace API before the first render), so it costs no request and no other language pays for it.
Dynamic accents (a place name in the results headline) use the platform serif instead: names are unbounded.

The accent strings are read from the translation files: every static `accent('…')` in src/i18n/<locale>/*.ts. Re-run
after changing one (a test fails when a static accent has glyphs the face lacks).

Usage: python3 scripts/build-accent-fonts.py   (needs: pip install fonttools brotli; network access to jsdelivr)
"""
import base64
import io
import re
import ssl
import urllib.request
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
VERSION = '5.3.1'
WEIGHT = 500
FAMILY = {'ja': 'noto-serif-jp', 'zh-Hans': 'noto-serif-sc', 'zh-Hant': 'noto-serif-tc', 'ko': 'noto-serif-kr'}
# A static accent: accent('…') or accent("…") with a literal, no interpolation.
ACCENT = re.compile(r"""accent\(\s*(?:'([^'\\$]*)'|"([^"\\$]*)")\s*\)""")


def fetch(url: str) -> bytes:
    ctx = ssl.create_default_context()
    bundle = Path('/root/.ccr/ca-bundle.crt')
    if bundle.exists():
        ctx.load_verify_locations(str(bundle))
    with urllib.request.urlopen(url, context=ctx, timeout=60) as r:
        return r.read()


def accent_text(locale: str) -> str:
    chars: set[str] = set()
    for f in sorted((ROOT / 'src' / 'i18n' / locale).glob('*.ts')):
        for m in ACCENT.finditer(f.read_text(encoding='utf-8')):
            chars.update(c for c in (m.group(1) or m.group(2) or '') if ord(c) > 0x2000)
    return ''.join(sorted(chars))


def slices(family: str) -> list[tuple[str, list[tuple[int, int]]]]:
    """The Fontsource slices of a family: (file name, unicode ranges)."""
    css = fetch(f'https://cdn.jsdelivr.net/npm/@fontsource/{family}@{VERSION}/{WEIGHT}.css').decode()
    out = []
    for block in css.split('@font-face')[1:]:
        file = re.search(r'url\(\./files/([^)]+?\.woff2)\)', block)
        rng = re.search(r'unicode-range:\s*([^;]+);', block)
        if not file or not rng:
            continue
        ranges = []
        for part in rng.group(1).split(','):
            a, _, b = part.strip()[2:].partition('-')
            ranges.append((int(a, 16), int(b or a, 16)))
        out.append((file.group(1), ranges))
    return out


def build(locale: str) -> None:
    text = accent_text(locale)
    target = ROOT / 'src' / 'i18n' / locale / 'accentFont.gen.ts'
    if not text:
        print(f'{locale}: no static accent')
        return
    family = FAMILY[locale]
    wanted = {ord(c) for c in text}
    files = sorted({f for f, rs in slices(family) for cp in wanted if any(a <= cp <= b for a, b in rs)})
    fonts = [TTFont(io.BytesIO(fetch(f'https://cdn.jsdelivr.net/npm/@fontsource/{family}@{VERSION}/files/{f}'))) for f in files]
    # One face per locale: the glyphs of each slice, subset, then merged when the words span slices.
    opts = subset.Options()
    opts.layout_features = ['palt', 'kern', 'vert']
    opts.name_IDs = [0, 1, 2, 3, 4, 5, 6, 13, 14]
    opts.hinting = False
    parts = []
    for font in fonts:
        have = {cp for cp in wanted if cp in font.getBestCmap()}
        if not have:
            continue
        sub = subset.Subsetter(options=opts)
        sub.populate(unicodes=sorted(have))
        sub.subset(font)
        parts.append(font)
    if len(parts) > 1:
        from fontTools.merge import Merger
        bufs = []
        for p in parts:
            b = io.BytesIO()
            p.save(b)
            b.seek(0)
            bufs.append(b)
        merged = Merger().merge(bufs)
    else:
        merged = parts[0]
    merged.flavor = 'woff2'
    out = io.BytesIO()
    merged.save(out)
    missing = [c for c in text if ord(c) not in merged.getBestCmap()]
    if missing:
        raise SystemExit(f'{locale}: no glyph for {missing!r}')
    b64 = base64.b64encode(out.getvalue()).decode()
    ranges = ','.join(f'U+{cp:X}' for cp in sorted(wanted))
    target.write_text(
        '/**\n'
        f' * Generated by scripts/build-accent-fonts.py from Noto Serif CJK ({family} {VERSION}, weight {WEIGHT}, SIL OFL 1.1):\n'
        f' * only the glyphs of this language\'s static serif accents ({text}). Do not edit; re-run the script.\n'
        ' */\n'
        f"export default {{ text: '{text}', unicodeRange: '{ranges}', woff2: '{b64}' }}\n",
        encoding='utf-8',
    )
    print(f'{locale}: {text} -> {target.relative_to(ROOT)} ({len(out.getvalue()):,} bytes woff2)')


def main() -> None:
    for locale in FAMILY:
        if (ROOT / 'src' / 'i18n' / locale).is_dir():
            build(locale)


if __name__ == '__main__':
    main()
